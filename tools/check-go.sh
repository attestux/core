#!/usr/bin/env bash
set -euo pipefail

go test -race -vet=all ./...
go test -vet=all -tags=attestux_simulator ./...

go tool staticcheck ./...
go tool staticcheck -tags=attestux_simulator ./...
CGO_ENABLED=1 go tool staticcheck -tags=tpmsimulator ./...
CGO_ENABLED=1 go tool staticcheck -tags=tpmsimulator,attestux_simulator ./...
CGO_ENABLED=1 go vet -tags=tpmsimulator ./...
CGO_ENABLED=1 go vet -tags=tpmsimulator,attestux_simulator ./...

unformatted="$(gofmt -l ./attestation ./mobilebind ./verifier)"
if [[ -n "${unformatted}" ]]; then
	echo "gofmt needed:" >&2
	echo "${unformatted}" >&2
	exit 1
fi
